//! The TypeScript rendering of the contract, compared byte for byte with
//! `src/lib/api/generated/` by `tests/drift.rs`.

use ts_rs::{Config, TS};

use crate::{
    ErrorBody, NoInput, ServerFunction,
    commerce::{CommerceReadiness, CommerceStorage, GetCommerceReadiness, PaymentMode},
    inquiries::{
        GetTurnstileConfig, InquiryCode, InquiryField, InquiryResult, SendInquiry,
        SendInquiryInput, TurnstileConfig,
    },
    quasar::GetQuasarDefaultOrigin,
};

/// Defaults, never the environment: the export must not depend on `TS_RS_*`.
fn cfg() -> Config {
    Config::new()
}

/// One line of `ServerFunctions`: the wire name and the TypeScript type names.
struct Entry {
    name: &'static str,
    input: String,
    result: String,
}

fn entry<F: ServerFunction>() -> Entry {
    Entry {
        name: F::NAME,
        input: <F::Input as TS>::name(&cfg()),
        result: <F::Output as TS>::name(&cfg()),
    }
}

/// Every server function in the contract, in declaration order.
fn functions() -> Vec<Entry> {
    vec![
        entry::<SendInquiry>(),
        entry::<GetTurnstileConfig>(),
        entry::<GetQuasarDefaultOrigin>(),
        entry::<GetCommerceReadiness>(),
    ]
}

/// The wire names of every function, for the name-format test.
pub fn function_names() -> Vec<&'static str> {
    functions().iter().map(|e| e.name).collect()
}

fn one<T: TS + 'static>(out: &mut Vec<(String, String)>) {
    let name = <T as TS>::ident(&cfg());
    let body = <T as TS>::export_to_string(&cfg())
        .unwrap_or_else(|e| format!("// export of {name} failed: {e}\n"));
    out.push((format!("{name}.ts"), body));
}

fn index(entries: &[Entry], type_files: &[(String, String)]) -> String {
    let mut s = String::from(
        "// This file was generated by quesar-contract. Do not edit it by hand.\n\
         // Regenerate: GEN_CONTRACT_TYPES=1 cargo test -p quesar-contract --test drift\n\n",
    );
    for (file, _) in type_files {
        let ty = file.trim_end_matches(".ts");
        s.push_str(&format!("import type {{ {ty} }} from \"./{ty}\";\n"));
    }
    s.push('\n');
    for (file, _) in type_files {
        let ty = file.trim_end_matches(".ts");
        s.push_str(&format!("export type {{ {ty} }};\n"));
    }
    s.push_str("\n/** Every server function: its input and its result, keyed by wire name. */\n");
    s.push_str("export interface ServerFunctions {\n");
    for e in entries {
        s.push_str(&format!(
            "  \"{}\": {{ input: {}; result: {} }};\n",
            e.name, e.input, e.result
        ));
    }
    s.push_str("}\n\nexport type ServerFunctionName = keyof ServerFunctions;\n");
    s
}

/// All generated files as `(file name, contents)`, `index.ts` last.
pub fn files() -> Vec<(String, String)> {
    let mut out = Vec::new();
    one::<ErrorBody>(&mut out);
    one::<NoInput>(&mut out);
    one::<SendInquiryInput>(&mut out);
    one::<InquiryField>(&mut out);
    one::<InquiryCode>(&mut out);
    one::<InquiryResult>(&mut out);
    one::<TurnstileConfig>(&mut out);
    one::<PaymentMode>(&mut out);
    one::<CommerceStorage>(&mut out);
    one::<CommerceReadiness>(&mut out);
    let idx = index(&functions(), &out);
    out.push(("index.ts".to_string(), idx));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn valid_name(name: &str) -> bool {
        let Some((module, function)) = name.split_once('.') else {
            return false;
        };
        let part = |s: &str| {
            let mut chars = s.chars();
            chars.next().is_some_and(|c| c.is_ascii_lowercase())
                && chars.all(|c| c.is_ascii_alphanumeric())
        };
        part(module) && part(function)
    }

    #[test]
    fn function_names_are_well_formed_and_unique() {
        let names = function_names();
        assert_eq!(names.len(), 4);
        for name in &names {
            assert!(valid_name(name), "bad function name {name}");
        }
        let mut sorted = names.clone();
        sorted.sort_unstable();
        sorted.dedup();
        assert_eq!(sorted.len(), names.len(), "duplicate function name");
    }

    #[test]
    fn name_checker_rejects_malformed_names() {
        for bad in ["", "a", "a.", ".b", "A.b", "a.B", "a.b.c", "a-b.c", "1a.b"] {
            assert!(!valid_name(bad), "{bad} should be rejected");
        }
    }

    #[test]
    fn index_lists_every_function() {
        let (_, index) = files().into_iter().find(|(n, _)| n == "index.ts").unwrap();
        for name in function_names() {
            assert!(
                index.contains(&format!("\"{name}\"")),
                "{name} missing from index.ts"
            );
        }
    }
}
