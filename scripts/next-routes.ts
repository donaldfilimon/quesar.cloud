#!/usr/bin/env node
/**
 * Generate the Next.js App Router pages (`app/**\/page.tsx` + `view.tsx`) from the
 * TanStack file routes in `src/routes`, so both builds render one set of routes
 * while the port runs (notes/superpowers/specs/2026-10-26-nextjs-app-router-port.md).
 *
 * Each route id comes from its `createFileRoute("…")` call, not the file name. The
 * server `page.tsx` supplies params (dynamic routes read `src/compat/next/static-params.ts`)
 * and renders the client `view.tsx`, which mounts the route through `RouteView`.
 *
 *   node scripts/next-routes.ts          write app/ (removes stale generated pages)
 *   node scripts/next-routes.ts --check  exit 1 if app/ is out of date
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const root = process.cwd();
const routesDir = join(root, "src", "routes");
const appDir = join(root, "app");
const MARKER = "// Generated by scripts/next-routes.ts";

/** Routes the static export cannot prerender yet, with the reason (stage 2 of the port). */
const DEFERRED: Record<string, string> = {
  "/quasar/site/$id": "per-user site ids exist only at runtime",
};

interface RouteFile {
  id: string;
  file: string;
  dynamic: string[];
}

function routeFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === "api" ? [] : routeFiles(path);
    if (!/\.tsx$/.test(entry.name) || entry.name.startsWith("-") || entry.name.startsWith("__"))
      return [];
    return [path];
  });
}

function readRoutes(): RouteFile[] {
  const routes: RouteFile[] = [];
  for (const path of routeFiles(routesDir)) {
    const source = readFileSync(path, "utf8");
    const id = source.match(/createFileRoute\("([^"]+)"\)/)?.[1];
    // Server-only routes (no component) have no page.
    if (!id || !/\bcomponent:/.test(source)) continue;
    if (id in DEFERRED) continue;
    const dynamic = [...id.matchAll(/\$([A-Za-z0-9_]+)/g)].map((m) => m[1]);
    routes.push({ id, file: relative(join(root, "src"), path).replace(/\.tsx$/, ""), dynamic });
  }
  return routes.sort((a, b) => a.id.localeCompare(b.id));
}

function segmentDir(id: string): string {
  const segments = id
    .split("/")
    .filter(Boolean)
    .map((part) => (part.startsWith("$") ? `[${part.slice(1)}]` : part));
  return join(appDir, ...segments);
}

function pageSource(route: RouteFile): string {
  const header = `${MARKER} from src/${route.file}.tsx. Do not edit.\n`;
  if (!route.dynamic.length) {
    return `${header}import RouteView from "./view";

export default function Page() {
  return <RouteView />;
}
`;
  }
  const params = route.dynamic.map((name) => `${name}: string`).join("; ");
  return `${header}import { staticParams } from "@/compat/next/static-params";
import RouteView from "./view";

export const dynamicParams = false;

export function generateStaticParams() {
  return staticParams[${JSON.stringify(route.id)}]();
}

export default async function Page({ params }: { params: Promise<{ ${params} }> }) {
  return <RouteView params={await params} />;
}
`;
}

function viewSource(route: RouteFile): string {
  return `"use client";
${MARKER} from src/${route.file}.tsx. Do not edit.
import { RouteView as Mount } from "@/compat/next/route-view";
import { Route } from "@/${route.file}";

export default function RouteView({ params }: { params?: Record<string, string> }) {
  return <Mount route={Route} params={params} />;
}
`;
}

function generatedFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return generatedFiles(path);
    return readFileSync(path, "utf8").includes(MARKER) ? [path] : [];
  });
}

const check = process.argv.includes("--check");
const wanted = new Map<string, string>();
for (const route of readRoutes()) {
  const dir = segmentDir(route.id);
  wanted.set(join(dir, "page.tsx"), pageSource(route));
  wanted.set(join(dir, "view.tsx"), viewSource(route));
}

const stale = generatedFiles(appDir).filter((path) => !wanted.has(path));
const changed = [...wanted].filter(
  ([path, source]) => !existsSync(path) || readFileSync(path, "utf8") !== source,
);

if (check) {
  const drift = [...stale, ...changed.map(([path]) => path)];
  if (drift.length) {
    console.error(
      `[next-routes] app/ is out of date; run \`node scripts/next-routes.ts\`:\n  ${drift
        .map((path) => relative(root, path))
        .join("\n  ")}`,
    );
    process.exit(1);
  }
  console.log(`[next-routes] app/ matches ${wanted.size / 2} routes`);
} else {
  for (const path of stale) rmSync(path);
  for (const [path, source] of changed) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, source);
  }
  console.log(
    `[next-routes] ${wanted.size / 2} routes: ${changed.length} files written, ${stale.length} removed; deferred: ${Object.keys(DEFERRED).join(", ")}`,
  );
}
