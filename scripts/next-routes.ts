#!/usr/bin/env node
/**
 * Generate the Next.js App Router pages (`app/**\/page.tsx` + `view.tsx`) from the
 * TanStack file routes in `src/routes`, so both builds render one set of routes
 * while the port runs (notes/superpowers/specs/2026-10-26-nextjs-app-router-port.md).
 *
 * Each route id comes from its `createFileRoute("…")` call, not the file name. The
 * server `page.tsx` supplies params (dynamic routes read `src/compat/next/static-params.ts`)
 * and renders the client `view.tsx`, which mounts the route through `RouteView`.
 *
 *   node scripts/next-routes.ts          write app/ (removes stale generated pages)
 *   node scripts/next-routes.ts --check  exit 1 if app/ is out of date
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { format, resolveConfig } from "prettier";

const root = process.cwd();
const routesDir = join(root, "src", "routes");
const appDir = join(root, "app");
const MARKER = "// Generated by scripts/next-routes.ts";

/**
 * Routes the static export cannot prerender, with the reason. They get a
 * `page.server.tsx`, which only the server build reads (`pageExtensions` in
 * next.config.ts), rendered per request.
 */
const SERVER_ONLY_PAGES: Record<string, string> = {
  "/quasar/site/$id": "per-user site ids exist only at runtime",
};

interface RouteFile {
  id: string;
  file: string;
  dynamic: string[];
  /** `server.handlers` methods, for server routes (no component). */
  methods: string[];
}

function routeFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return routeFiles(path);
    if (!/\.tsx?$/.test(entry.name) || entry.name.startsWith("-") || entry.name.startsWith("__"))
      return [];
    return [path];
  });
}

function readRoutes(): RouteFile[] {
  const routes: RouteFile[] = [];
  for (const path of routeFiles(routesDir)) {
    const source = readFileSync(path, "utf8");
    const id = source.match(/createFileRoute\("([^"]+)"\)/)?.[1];
    if (!id) continue;
    const isPage = /\bcomponent:/.test(source);
    const methods = isPage
      ? []
      : [...source.matchAll(/\b(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\s*[:(]/g)].map((m) => m[1]);
    if (!isPage && !methods.length) continue;
    const dynamic = [...id.matchAll(/\$([A-Za-z0-9_]+)/g)].map((m) => m[1]);
    routes.push({
      id,
      file: relative(join(root, "src"), path).replace(/\.tsx?$/, ""),
      dynamic,
      methods: [...new Set(methods)],
    });
  }
  return routes.sort((a, b) => a.id.localeCompare(b.id));
}

function segmentDir(id: string): string {
  const segments = id
    .split("/")
    .filter(Boolean)
    .map((part) =>
      part === "$" ? "[..._splat]" : part.startsWith("$") ? `[${part.slice(1)}]` : part,
    );
  return join(appDir, ...segments);
}

function pageSource(route: RouteFile): string {
  const header = `${MARKER} from src/${route.file}.tsx. Do not edit.\n`;
  if (!route.dynamic.length) {
    return `${header}import RouteView from "./view";

export default function Page() {
  return <RouteView />;
}
`;
  }
  const params = route.dynamic.map((name) => `${name}: string`).join("; ");
  return `${header}import { staticParams } from "@/compat/next/static-params";
import RouteView from "./view";

export const dynamicParams = false;

export function generateStaticParams() {
  return staticParams[${JSON.stringify(route.id)}]();
}

export default async function Page({ params }: { params: Promise<{ ${params} }> }) {
  return <RouteView params={await params} />;
}
`;
}

function serverPageSource(route: RouteFile): string {
  const params = route.dynamic.map((name) => `${name}: string`).join("; ");
  return `${MARKER} from src/${route.file}.tsx. Do not edit.
// Server build only (${SERVER_ONLY_PAGES[route.id]}).
import RouteView from "./view";

export const dynamic = "force-dynamic";

export default async function Page({ params }: { params: Promise<{ ${params} }> }) {
  return <RouteView params={await params} />;
}
`;
}

function serverRouteSource(route: RouteFile): string {
  const exports = route.methods
    .map((method) => `export const ${method} = routeHandler(Route, ${JSON.stringify(method)});`)
    .join("\n");
  return `${MARKER} from src/${route.file}.ts. Do not edit.
// Server build only: the \`.server.ts\` extension keeps it out of the static export.
import { routeHandler } from "@/compat/next/api-route";
import { Route } from "@/${route.file}";

export const dynamic = "force-dynamic";

${exports}
`;
}

/** Every module that defines a server function, so the dispatcher registers them all. */
function serverFnManifest(): string {
  const modules: string[] = [];
  const scan = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (!["routes", "compat"].includes(entry.name)) scan(path);
      } else if (/\.tsx?$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name)) {
        if (/\bcreateServerFn\(\s*[{)]/.test(readFileSync(path, "utf8")))
          modules.push(relative(join(root, "src"), path).replace(/\.tsx?$/, ""));
      }
    }
  };
  scan(join(root, "src"));
  const sorted = modules.sort();
  // Namespace imports the dispatcher reads: package.json sets "sideEffects": false,
  // so bare \`import "…"\` lines would be dropped and nothing would register.
  return `${MARKER}. Do not edit.
// Imported by ./route.server.ts so every server function is registered.
${sorted.map((module, index) => `import * as module${index} from "@/${module}";`).join("\n")}

export const serverFnModules = [${sorted.map((_, index) => `module${index}`).join(", ")}];
`;
}

function viewSource(route: RouteFile): string {
  return `"use client";
${MARKER} from src/${route.file}.tsx. Do not edit.
import { RouteView as Mount } from "@/compat/next/route-view";
import { Route } from "@/${route.file}";

export default function RouteView({ params }: { params?: Record<string, string> }) {
  return <Mount route={Route} params={params} />;
}
`;
}

function generatedFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return generatedFiles(path);
    return readFileSync(path, "utf8").includes(MARKER) ? [path] : [];
  });
}

const check = process.argv.includes("--check");
const wanted = new Map<string, string>();
for (const route of readRoutes()) {
  const dir = segmentDir(route.id);
  if (route.methods.length) {
    // A hand-written static route handler (`app/feed.xml/route.ts`) serves both builds.
    if (!existsSync(join(dir, "route.ts")))
      wanted.set(join(dir, "route.server.ts"), serverRouteSource(route));
    continue;
  }
  wanted.set(
    join(dir, route.id in SERVER_ONLY_PAGES ? "page.server.tsx" : "page.tsx"),
    route.id in SERVER_ONLY_PAGES ? serverPageSource(route) : pageSource(route),
  );
  wanted.set(join(dir, "view.tsx"), viewSource(route));
}
wanted.set(join(appDir, "api", "server-fn", "[id]", "manifest.ts"), serverFnManifest());

// Generated files are committed and pass `format:check`, so they are written formatted.
for (const [path, source] of wanted) {
  const options = (await resolveConfig(path)) ?? {};
  wanted.set(path, await format(source, { ...options, filepath: path }));
}

const stale = generatedFiles(appDir).filter((path) => !wanted.has(path));
const changed = [...wanted].filter(
  ([path, source]) => !existsSync(path) || readFileSync(path, "utf8") !== source,
);

if (check) {
  const drift = [...stale, ...changed.map(([path]) => path)];
  if (drift.length) {
    console.error(
      `[next-routes] app/ is out of date; run \`node scripts/next-routes.ts\`:\n  ${drift
        .map((path) => relative(root, path))
        .join("\n  ")}`,
    );
    process.exit(1);
  }
  console.log(`[next-routes] app/ matches ${wanted.size} generated files`);
} else {
  for (const path of stale) rmSync(path);
  for (const [path, source] of changed) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, source);
  }
  console.log(
    `[next-routes] ${wanted.size} generated files: ${changed.length} written, ${stale.length} removed; server-only pages: ${Object.keys(SERVER_ONLY_PAGES).join(", ")}`,
  );
}
